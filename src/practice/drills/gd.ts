const VOWEL = /^[aeiouàèìòù]/i;
const lenite = (noun: string) => (/^([bcdfgmpt]|s[aeiouàèìòùlnr])/i.test(noun) && noun[1] !== 'h' ? `${noun[0]}h${noun.slice(1)}` : noun);

/**
 * The article on a noun, by its gender and first letters, as lesson 3 teaches it: masculine an, am
 * before b f m p, an t- before a vowel; feminine a’ and lenition, an t- before s and a vowel or sl sn sr.
 */
function article(noun: string, gender: string): { text: string; why: string } {
  if (gender === 'm') {
    if (VOWEL.test(noun)) return { text: `an t-${noun}`, why: `${noun} is masculine and starts with a vowel, so it takes an t-` };
    if (/^[bfmp]/i.test(noun)) return { text: `am ${noun}`, why: `${noun} is masculine and starts with ${noun[0]}, so it takes am (before b, f, m and p)` };
    return { text: `an ${noun}`, why: `${noun} is masculine, so it takes an` };
  }
  if (/^s([aeiouàèìòù]|[lnr])/i.test(noun)) return { text: `an t-${noun}`, why: `${noun} is feminine and starts with s${/^s[lnr]/i.test(noun) ? noun[1] : ' and a vowel'}, so it takes an t-` };
  if (/^[bcgmp]/i.test(noun)) return { text: `a’ ${lenite(noun)}`, why: `${noun} is feminine, so it takes a’ and lenites: ${noun} → a’ ${lenite(noun)}` };
  if (/^f/i.test(noun)) return { text: `an ${lenite(noun)}`, why: `${noun} is feminine and starts with f, so it takes an and lenites, the fh silent` };
  return { text: `an ${noun}`, why: `${noun} is feminine, but starts with a letter a’ doesn’t go before, so it takes an` };
}

